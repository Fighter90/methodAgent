@pytest.mark.parametrize(('text', 'code'), AUDIENCE)
def test_ps_for_audience(text: str, code: str) -> None:
    """SPEC-KB-16"""
    ps = pick_ps(text)
    assert ps is not None and ps.code == code
    assert ps.confirmed and 0 < len(ps.tf) <= 12


def test_audience_keywords_keep_open_cases() -> None:
    """SPEC-KB-16, SPEC-KB-05"""
    assert {cid: pick_ps(CASES[cid]).code for cid in (2, 3, 4, 5)} == {2: '01.001', 3: '06.042', 4: '06.033', 5: '06.026'}

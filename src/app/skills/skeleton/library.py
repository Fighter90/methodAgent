def pick_domain(text: str) -> Domain | None:
    low = text.lower()
    best, best_score = None, 0
    for d in DOMAINS:
        if d.get('requires_any') and not any(k in low for k in d['requires_any']):
            continue
        score = sum(1 for kw in d['keywords'] if kw in low)
        if score > best_score:
            best, best_score = d, score
    return best



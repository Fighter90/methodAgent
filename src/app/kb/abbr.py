"""Расшифровка сокращений образования в поисковом запросе: «педагог ДО» ищет и «дополнительного образования».

Сокращение распознаётся только целым словом в верхнем регистре, поэтому предлог «до» не расширяется.
"""

from __future__ import annotations

import re

ABBR: dict[str, str] = {
    'ДО': 'дополнительное образование детей',
    'ДОД': 'дополнительное образование детей',
    'ДПО': 'дополнительное профессиональное образование',
    'ДООП': 'дополнительная общеобразовательная общеразвивающая программа',
    'ДПП': 'дополнительная профессиональная программа',
    'ПК': 'повышение квалификации',
    'ПП': 'профессиональная переподготовка',
    'СПО': 'среднее профессиональное образование',
    'ВО': 'высшее образование',
    'ПС': 'профессиональный стандарт',
    'ФГОС': 'федеральный государственный образовательный стандарт',
    'ОВЗ': 'ограниченные возможности здоровья',
    'ГИА': 'государственная итоговая аттестация',
    'ИА': 'итоговая аттестация',
    'ДОТ': 'дистанционные образовательные технологии',
    'ЭО': 'электронное обучение',
    'ОО': 'образовательная организация',
    'ТФ': 'трудовая функция',
    'ОТФ': 'обобщённая трудовая функция',
    'УТП': 'учебно-тематический план',
    'КУГ': 'календарный учебный график',
    'ФОС': 'фонд оценочных средств',
}
_TOKEN = re.compile(r'(?<![\wА-Яа-яЁё])([А-ЯЁ]{2,5})(?![\wА-Яа-яЁё])')


def expand(query: str) -> str:
    """Запрос с расшифровками найденных сокращений в конце; без сокращений — как есть."""
    extra = [ABBR[t] for t in dict.fromkeys(_TOKEN.findall(query)) if t in ABBR]
    return f'{query} ({"; ".join(extra)})' if extra else query
